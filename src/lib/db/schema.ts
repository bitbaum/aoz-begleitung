/**
 * Drizzle schema — SSOT for tables, enums and (via types.ts) derived types.
 *
 * EXACT parity with the live database, whose shape was created by the 29
 * Prisma migrations in the repo's history: table/column names are Prisma's
 * PascalCase/camelCase ("PlacementSpot", "createdAt"), enums keep their
 * Prisma type names ("AgeRange"), ids are TEXT minted app-side, timestamps
 * are TIMESTAMP(3), and every index/FK/unique constraint name is pinned to
 * the one Prisma generated ("Resident_code_key", "Placement_residentId_fkey",
 * …) so a fresh database and the live one are byte-identical. Do not
 * "normalize" any of this — the schema must match the database that exists,
 * and the deploy pipeline refuses destructive diffs.
 *
 * Prisma generated cuid() ids and @updatedAt client-side; the equivalents
 * here are $defaultFn(createId) (@paralleldrive/cuid2) and
 * $defaultFn/$onUpdateFn — also app-side, so the columns carry no new DB
 * defaults. Initially generated by drizzle-kit pull against a database built
 * by the Prisma migration chain, then verified by a normalized pg_dump diff
 * (see PR #<n>).
 */

