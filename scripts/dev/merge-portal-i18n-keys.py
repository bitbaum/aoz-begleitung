LOCALE_MAP: dict[str, dict[str, str]] = {
    "de": DE,
    "en": EN,
    "fr": FR,
    "uk": UK,
    "ru": RU,
    "ar": AR,
}


def escape_ts(s: str) -> str:
    return s.replace("\\", "\\\\").replace("'", "\\'")


def format_entry(key: str, value: str) -> str:
    if "\n" in value:
        return f"  '{key}':\n    '{escape_ts(value)}',"
    return f"  '{key}': '{escape_ts(value)}',"


def existing_keys(content: str) -> set[str]:
    return set(re.findall(r"^\s+'([^']+)':", content, re.MULTILINE))


def merge_locale(locale: str, translations: dict[str, str]) -> None:
    path = DICT_DIR / f"{locale}.ts"
    content = path.read_text(encoding="utf-8")
    present = existing_keys(content)
    missing = {k: v for k, v in translations.items() if k not in present}
    if not missing:
        print(f"{locale}: nothing to add")
        return

    block = "\n  // Portal surfaces (expenses, profile, transfer, preferences)\n"
    block += "\n".join(format_entry(k, v) for k, v in sorted(missing.items()))
    block += "\n"

    if locale == "de":
        content = content.replace("\n} as const", block + "} as const", 1)
    else:
        content = content.rstrip()
        if content.endswith("}"):
            content = content[:-1].rstrip() + "\n" + block + "}\n"
        else:
            raise SystemExit(f"Unexpected format in {path}")

    path.write_text(content, encoding="utf-8")
    print(f"{locale}: added {len(missing)} keys")


def main() -> None:
    for locale, translations in LOCALE_MAP.items():
        merge_locale(locale, translations)


if __name__ == "__main__":
    main()
